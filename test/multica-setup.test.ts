test('concurrent setup cannot duplicate the same private instance and the lock is released after failure', async t => {
  const state = await mkdtemp(resolve(tmpdir(), 'gwi-setup-lock-')); t.after(() => rm(state, {recursive: true, force: true}));
  let release!: () => void;
  const gate = new Promise<void>(resolve => {release = resolve;});
  let entered!: () => void; const started = new Promise<void>(resolve => {entered = resolve;});
  const first = setup.withSetupLock(state, async () => {entered(); await gate; throw new Error('synthetic failure');});
  await started;
  await assert.rejects(setup.withSetupLock(state, async () => 'must-not-run'), {step: 'setup-lock'});
  release(); await assert.rejects(first, /synthetic failure/);
  assert.equal(await setup.withSetupLock(state, async () => 'recovered'), 'recovered');
});

